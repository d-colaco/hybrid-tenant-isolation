def protect(table: str, read_exception: bool = False) -> None:
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY tenant_isolation ON {table} USING (tenant_id = app.current_tenant()) "
        "WITH CHECK (tenant_id = app.current_tenant())"
    )
    if read_exception:
        op.execute(f"CREATE POLICY cross_tenant_read ON {table} FOR SELECT USING (app.in_scope(tenant_id))")
    op.execute(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {table} TO lab_app")


